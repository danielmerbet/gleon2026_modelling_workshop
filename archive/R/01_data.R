# =============================================================================
# RESHAPE: pivot all raw tables to long format and join into master tibble
# =============================================================================

pivot_var <- function(df, station, variable) {
  df |>
    pivot_longer(cols = Jan:Dec, names_to = "month_name", values_to = variable) |>
    mutate(station = station,
           month = match(month_name, month.abb))
}

ciii_data <- list(
  pivot_var(temp_CIII_raw,  "CIII", "temp_C"),
  pivot_var(do_CIII_raw,    "CIII", "DO_mgl"),
  pivot_var(chla_CIII_raw,  "CIII", "chla_ugl"),
  pivot_var(no3_CIII_raw,   "CIII", "NO3_N"),
  pivot_var(nh4_CIII_raw,   "CIII", "NH4_N"),
  pivot_var(ph_CIII_raw,    "CIII", "pH")
) |>
  reduce(full_join, by = c("depth_m", "month_name", "station", "month"))

civ_data <- list(
  pivot_var(temp_CIV_raw,   "CIV",  "temp_C"),
  pivot_var(do_CIV_raw,     "CIV",  "DO_mgl"),
  pivot_var(chla_CIV_raw,   "CIV",  "chla_ugl")
) |>
  reduce(full_join, by = c("depth_m", "month_name", "station", "month"))

banyoles <- bind_rows(ciii_data, civ_data) |>
  left_join(meteo_banyoles |> select(month, air_temp_C, precip_mm), by = "month") |>
  arrange(station, depth_m, month) |>
  select(station, month, month_name, depth_m, temp_C, DO_mgl, chla_ugl,
         pH, NO3_N, NH4_N, air_temp_C, precip_mm)

message("Dataset loaded: ", nrow(banyoles), " rows, ", ncol(banyoles), " columns")
